/* look100/ingame/mkgame8.js — ROUND 8 PREVIEW bundler: like tools/art/rig92/mkgame.js, but from ingame/rig92/ (the look-test body, gear,
   holds and the r8 SDF sculpts) into ingame/assets/tok93.js only. The committed assets/tok93.js and tools/art/rig92 stay untouched.
   Adds 'sculpt' to the modules and understands `export { a as b }`. */
const fs = require('fs'), path = require('path');
const HERE = path.join(__dirname, 'rig92'), OUT = path.join(__dirname, 'assets');
const MODS = ['rig', 'body', 'presets', 'gear', 'sculpt', 'game'];
let out = '/* ingame/assets/tok93.js — PREVIEW, GENERATED by tools/plans/look100/ingame/mkgame8.js (look100 round 8). Not the release bundle. */\n'
  + 'window.TOK93LIB=function(THREE){"use strict";const __M={};\n';
for (const m of MODS) {
  let src = fs.readFileSync(path.join(HERE, m + '.js'), 'utf8'); const names = [];
  src = src.replace(/^import \* as THREE from 'three';\s*$/m, '');
  src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/(\w+)\.js';\s*$/mg, (_, list, mod) => 'const {' + list.split(',').map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ':')).join(',') + '}=__M.' + mod + ';');
  src = src.replace(/^export\s+((?:async\s+)?function\*?\s+(\w+))/mg, (_, decl, n) => { names.push(n); return decl; });
  src = src.replace(/^export\s+(const|let)\s+(\w+)/mg, (_, k, n) => { names.push(n); return k + ' ' + n; });
  src = src.replace(/^export\s*\{([^}]*)\};?\s*$/mg, (_, list) => { names.push(...list.split(',').map(s => s.trim()).filter(Boolean).map(s => { const r = /^(\S+)\s+as\s+(\S+)$/.exec(s); return r ? r[2] + ':' + r[1] : s; })); return ''; });
  if (/^\s*(import|export)\b/m.test(src)) throw new Error(m + ': import/export left');
  out += `__M.${m}=(function(){\n${src}\nreturn {${names.join(',')}};})();\n`;
}
out += 'return __M.game;};\n';
fs.writeFileSync(path.join(OUT, 'tok93.js'), out);
console.log('tok93.js (preview)', out.length, 'B');
