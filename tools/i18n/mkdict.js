/* merges tools/i18n/es/part-*.json → src/00-lang-es.js (one entry per line). Keys whose value equals the key are kept
   (they mark "same in Spanish", so the walk test does not count them as misses). Part 25 = server texts: its keys with
   {n} also go into LANG_SRVPAT_ES (the client matches server messages against them, 148-v86lang TXP). */
const fs=require('fs'),path=require('path');
const dir=path.join(__dirname,'es');const all={};const srvPat=[];let n=0;
for(const f of fs.readdirSync(dir).filter(f=>/^part-\d+\.json$/.test(f)).sort()){
  const o=JSON.parse(fs.readFileSync(path.join(dir,f),'utf8'));
  for(const [k,v] of Object.entries(o)){if(typeof v!=='string')continue;all[k]=v;n++;if(f==='part-25.json'&&/\{\d+\}/.test(k))srvPat.push(k)}}
const keys=Object.keys(all).sort();
const lines=keys.map(k=>JSON.stringify(k)+':'+JSON.stringify(all[k]));
const head=`/* 00-lang-es — v0.86 Spanish (neutral Latin-American, tú). GENERATED by tools/i18n/mkdict.js from tools/i18n/es/*.json —
   edit the parts, not this file. Keys = the English text (see 00-lang); values keep every {n}, tag and attribute,
   and keep game terms + names in English. ${keys.length} entries. */\n`;
const body=`const LANG_ES={\n${lines.join(',\n')}\n};\nconst LANG_SRVPAT_ES=${JSON.stringify(srvPat)};\nif(LANG==='es')LANG_DICT=LANG_ES;\n`;
fs.writeFileSync(path.join(__dirname,'..','..','src','00-lang-es.js'),head+body);
console.log('00-lang-es.js',keys.length,'entries',srvPat.length,'server patterns',Math.round((head+body).length/1024)+' KB');
