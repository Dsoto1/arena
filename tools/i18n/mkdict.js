/* v0.87: merges tools/i18n/<lang>/part-*.json → assets/lang_<lang>.js, one file per language, loaded ONLY when that language is
   picked (01-head's loader: document.write of the script before the game's own script; the standalone share build carries them
   as data URIs in window.ASSET_DATA). Each file sets window.LANG_PACK={l,d:{english key → text},s:[server patterns]}.
   Keys whose value equals the key are kept (they mark "same in this language", so the walk test does not count them as misses).
   Part 25 = server texts: its keys with {n} also go into s (148-v86lang TXP matches server messages against them).
   Usage: node tools/i18n/mkdict.js [lang …]   (no argument = every language folder that has parts) */
const fs=require('fs'),path=require('path');
const ROOT=path.join(__dirname,'..','..');
const LANGS=process.argv.slice(2).length?process.argv.slice(2):fs.readdirSync(__dirname).filter(d=>/^[a-z]{2}$/.test(d)&&fs.statSync(path.join(__dirname,d)).isDirectory());
for(const L of LANGS){
  const dir=path.join(__dirname,L);const all={};const srvPat=[];
  for(const f of fs.readdirSync(dir).filter(f=>/^part-\d+\.json$/.test(f)).sort()){
    const o=JSON.parse(fs.readFileSync(path.join(dir,f),'utf8'));
    for(const [k,v] of Object.entries(o)){if(typeof v!=='string')continue;all[k]=v;if(f==='part-25.json'&&/\{\d+\}/.test(k))srvPat.push(k)}}
  const keys=Object.keys(all).sort();
  const body=`/* lang_${L} — GENERATED by tools/i18n/mkdict.js from tools/i18n/${L}/*.json; edit the parts, not this file. ${keys.length} entries. */\n`+
    `window.LANG_PACK={l:${JSON.stringify(L)},d:{\n${keys.map(k=>JSON.stringify(k)+':'+JSON.stringify(all[k])).join(',\n')}\n},s:${JSON.stringify(srvPat)}};\n`;
  const out=path.join(ROOT,'assets','lang_'+L+'.js');fs.writeFileSync(out,body);
  console.log('assets/lang_'+L+'.js',keys.length,'entries',srvPat.length,'server patterns',Math.round(body.length/1024)+' KB');
}
