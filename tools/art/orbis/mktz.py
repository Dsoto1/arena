"""Write src/online/117-onltz.js: ONL_TZ {IANA zone: [lat, lon]} from the public-domain tz database.
Usage (from the repo root):  python3 tools/art/orbis/mktz.py [zoneinfo dir=/usr/share/zoneinfo]
Sources: zone1970.tab (every zone, with its principal city's coordinates), zone.tab (per-country zones it adds),
and the links in tzdata.zi (old names browsers still report, e.g. Asia/Calcutta, Europe/Kiev, US/Eastern) -> their target's place.
Coordinates are ±DDMM[SS]±DDDMM[SS]; written rounded to 0.1 degree, ~10 zones per line."""
import os, re, sys

ZI = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'src', 'online', '117-onltz.js')

def dms(s, deg):
    sign = -1 if s[0] == '-' else 1
    s = s[1:]
    d, m, sec = int(s[:deg]), int(s[deg:deg + 2]), int(s[deg + 2:deg + 4] or 0)
    return sign * (d + m / 60 + sec / 3600)

def coords(c):
    m = re.match(r'^([+-]\d{4}(?:\d{2})?)([+-]\d{5}(?:\d{2})?)$', c)
    if not m: raise ValueError(c)
    return dms(m.group(1), 2), dms(m.group(2), 3)

tz = {}
for fn in ('zone1970.tab', 'zone.tab'):
    for line in open(os.path.join(ZI, fn), encoding='utf-8'):
        if line.startswith('#') or not line.strip(): continue
        f = line.rstrip('\n').split('\t')
        if f[2] not in tz: tz[f[2]] = coords(f[1])
version = '?'
links = {}
for line in open(os.path.join(ZI, 'tzdata.zi'), encoding='utf-8'):
    if line.startswith('# version'): version = line.split()[-1]
    if line.startswith('L '):
        _, target, name = line.split()
        links[name] = target
SKIP = re.compile(r'^(Etc/|SystemV/|GMT|UTC|UCT|Universal|Zulu|Greenwich)')
added = 0
for name, target in sorted(links.items()):
    if name in tz or SKIP.match(name): continue
    seen = set()
    while target not in tz and target in links and target not in seen:
        seen.add(target); target = links[target]
    if target in tz:
        tz[name] = tz[target]; added += 1

def num(v):
    s = ('%.1f' % v).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s

items = ["'%s':[%s,%s]" % (k, num(la), num(lo)) for k, (la, lo) in sorted(tz.items())]
rows = [','.join(items[i:i + 10]) for i in range(0, len(items), 10)]
js = """/* =====================================================================
   117-ONLTZ · TIME ZONES → MAP POINTS (v0.80): ONL_TZ {IANA zone: [lat, lon]} for the Orbis Terrarum map (filled by the art step)
   Generated by tools/art/orbis/mktz.py from the public-domain tz database (tzdata %s): zone1970.tab + zone.tab coordinates,
   plus old link names browsers still report (Asia/Calcutta, Europe/Kiev, US/Eastern …) at their target's place. %d zones.
   onlTzLL(tz) → [lat, lon] or null (unknown zones still count online, they just get no dot); onlTzXY(tz) → map fractions [x, y].
   Map: x = (lon+180)/360, y = (76-lat)/128 on assets/orbis.webp (equirectangular, lat 76 … -52).
   ===================================================================== */
const ONL_TZ={
%s};
let ONL_TZLC=null;
/* zone names come from other players (via the server): own keys only, never __proto__/constructor */
function onlTzLL(tz){if(!tz||typeof tz!=='string'||tz.length>64)return null;const k=tz.trim().replace(/ /g,'_');
  if(Object.prototype.hasOwnProperty.call(ONL_TZ,k))return ONL_TZ[k];
  if(!ONL_TZLC){ONL_TZLC=new Map();for(const z in ONL_TZ)ONL_TZLC.set(z.toLowerCase(),ONL_TZ[z])}return ONL_TZLC.get(k.toLowerCase())||null}
/* → [x, y] as fractions of assets/orbis.webp, or null; far-north/south zones (Thule, Ushuaia, Antarctica) pinned just inside the edge */
function onlTzXY(tz){const ll=onlTzLL(tz);if(!ll)return null;const la=Math.max(-51,Math.min(75,ll[0]));
  return [(ll[1]+180)/360,(76-la)/128]}
""" % (version, len(items), ',\n'.join(rows))
open(OUT, 'w', encoding='utf-8').write(js)
print(os.path.normpath(OUT), len(items), 'zones (', added, 'links ),', len(js.encode()), 'bytes')
