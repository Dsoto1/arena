/* rig92/mkgame.js — bundles the token modeller for the game (v0.93):
     assets/three93.js  three.js r169 (vendor/three.module.min.js) as a plain script → window.THREE93
     assets/tok93.js    rig.js + body.js + presets.js + gear.js + game.js as a plain script → window.TOK93LIB(THREE) = game.js's exports
   Plain scripts (not ES modules) so they load from file:// pages and from the standalone's data: URLs alike.
   Run after editing any of those files:  node tools/art/rig92/mkgame.js */
const fs = require('fs'), path = require('path');
const HERE = __dirname, OUT = path.resolve(HERE, '../../../assets');

/* ---- three ---- */
let three = fs.readFileSync(path.join(HERE, 'vendor/three.module.min.js'), 'utf8');
const ex = three.lastIndexOf('export{'); if (ex < 0) throw new Error('three: no export block');
const end = three.indexOf('}', ex);
const pairs = three.slice(ex + 7, end).split(',').map(s => s.trim()).filter(Boolean).map(s => { const m = /^(\S+)\s+as\s+(\S+)$/.exec(s); return m ? [m[2], m[1]] : [s, s]; });
if (/\bimport\s*[{*(]|import\.meta/.test(three.slice(0, ex))) throw new Error('three: has imports');
const head = three.slice(0, three.indexOf('*/') + 2);
three = head + '\n(function(){' + three.slice(head.length, ex) + '\nwindow.THREE93={' + pairs.map(([k, v]) => k + ':' + v).join(',') + '};})();\n';
fs.writeFileSync(path.join(OUT, 'three93.js'), three);

/* ---- the modeller ---- */
const MODS = ['rig', 'body', 'presets', 'gear', 'game'];
let out = '/* assets/tok93.js — GENERATED by tools/art/rig92/mkgame.js from tools/art/rig92/{' + MODS.join(',') + '}.js (v0.93 token modeller). Edit those, then re-run. */\n'
  + 'window.TOK93LIB=function(THREE){"use strict";const __M={};\n';
for (const m of MODS) {
  let src = fs.readFileSync(path.join(HERE, m + '.js'), 'utf8');
  const names = [];
  src = src.replace(/^import \* as THREE from 'three';\s*$/m, '');
  src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/(\w+)\.js';\s*$/mg, (_, list, mod) => 'const {' + list.split(',').map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ':')).join(',') + '}=__M.' + mod + ';');
  src = src.replace(/^export\s+((?:async\s+)?function\*?\s+(\w+))/mg, (_, decl, n) => { names.push(n); return decl; });
  src = src.replace(/^export\s+(const|let)\s+(\w+)/mg, (_, k, n) => { names.push(n); return k + ' ' + n; });
  src = src.replace(/^export\s*\{([^}]*)\};?\s*$/mg, (_, list) => { names.push(...list.split(',').map(s => s.trim()).filter(Boolean)); return ''; });
  if (/^\s*(import|export)\b/m.test(src)) throw new Error(m + ': import/export left');
  out += `__M.${m}=(function(){\n${src}\nreturn {${names.join(',')}};})();\n`;
}
out += 'return __M.game;};\n';
fs.writeFileSync(path.join(OUT, 'tok93.js'), out);
console.log('three93.js', fs.statSync(path.join(OUT, 'three93.js')).size, 'B · tok93.js', out.length, 'B');
